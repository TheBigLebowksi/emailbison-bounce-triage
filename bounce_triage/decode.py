"""Step 2: decode a bounce into codes, who rejected it, and a code-book category.

Order of evidence: the RFC 3464 delivery-status part of raw_body, then the
human text (text_body, then html_body without tags). Only the remote server's
response (the diagnostic) is classified, never the whole NDR: NDR boilerplate
contains words like 'policy' and 'blocked' on its own.
"""
from __future__ import annotations

import email
import email.policy
import html
import re
from typing import Any

from .models import Bounce, Decoded

CODE = re.compile(r"\b([245]\d\d)[ -]([245]\.\d{1,3}\.\d{1,3})\b")          # 550 5.1.1 and Gmail's 550-5.1.1
ENHANCED = re.compile(r"(?<![\d.])#?([245]\.\d{1,3}\.\d{1,3})\b")
BASIC = re.compile(r"(?<![\d.#-])\b(42[01]|45[0-4]|55[0-4])\b(?![.\d])")
TAG = re.compile(r"\[((?:TSS|TS|PH|BL|GL|DM|IPTS|RL)\d{2})\]")             # Yahoo [TSS04], [PH01], ...

GENERATORS = [  # who wrote the NDR; checked in this order
    ("microsoft", re.compile(r"Undeliverable:|Diagnostic information for administrators|Remote Server returned|"
                             r"Delivery has failed to these recipients|couldn't be delivered|DSN generated by|"
                             r"Reported error:", re.I)),
    ("postfix", re.compile(r"This is the mail system at host|\(in reply to (RCPT TO|end of DATA|MAIL FROM) command\)|"
                           r"said:\s*[245]\d\d", re.I)),
    ("google", re.compile(r"mailer-daemon@googlemail\.com|Mail Delivery Subsystem|The response (from the remote "
                          r"server )?was:|Address not found|Message not delivered|gmail\.com/mail/\?p=", re.I)),
]
PROVIDER_MARKERS = [  # who rejected the mail; read from the diagnostic and Remote-MTA only
    ("mimecast", re.compile(r"mimecast", re.I)),
    ("proofpoint", re.compile(r"pphosted|ppe-hosted|proofpoint", re.I)),
    ("barracuda", re.compile(r"barracuda", re.I)),
    ("yahoo", re.compile(r"yahoo|yahoodns|\baol\.com|\[(TSS|TS|PH|BL)\d\d\]", re.I)),
    ("microsoft", re.compile(r"outlook\.com|protection\.outlook|RESOLVER\.|\bAS\(\d+\)|hotmail|exchangelabs", re.I)),
    ("google", re.compile(r"gsmtp|google\.com|googlemail", re.I)),
]
DIAGNOSTIC_PATTERNS = [
    re.compile(r"The response (?:from the remote server )?was:\s*(.+?)(?:\n\s*\n|-{3,}|\Z)", re.I | re.S),  # Gmail
    re.compile(r"Remote Server returned '(.+?)'[ \t]*(?:\n|\Z)", re.I | re.S),                          # Exchange
    re.compile(r"Reported error:\s*(.+?)(?:\n|\Z)", re.I | re.S),                                       # Exchange
    re.compile(r"(?:host|server) \S+ said:\s*(.+?\(in reply to [A-Z ]+command\))", re.I | re.S),        # Postfix
    re.compile(r"Diagnostic-Code:\s*(?:smtp;)?\s*(.+?)(?:\n\S|\Z)", re.I | re.S),
]
DSN_FIELDS = ("Reporting-MTA", "Remote-MTA", "Status", "Diagnostic-Code", "Action", "Final-Recipient")


def strip_html(text: str) -> str:
    text = re.sub(r"(?is)<(script|style).*?</\1>", " ", text or "")
    text = re.sub(r"(?i)<br\s*/?>|</p>|</div>|</tr>", "\n", text)
    return html.unescape(re.sub(r"<[^>]+>", " ", text))


def squash(text: str) -> str:
    return re.sub(r"\s+", " ", text or "").strip()


def parse_dsn(raw: str) -> dict[str, str]:
    """Parse the RFC 3464 message/delivery-status part of a raw MIME message ('_text' = human part)."""
    out: dict[str, str] = {}
    if not raw or "delivery-status" not in raw.lower():
        return out
    msg = email.message_from_string(raw, policy=email.policy.compat32)
    for part in msg.walk():
        ctype = part.get_content_type()
        if ctype == "message/delivery-status":
            payload = part.get_payload()
            blocks = payload if isinstance(payload, list) else [email.message_from_string(str(payload))]
            for block in blocks:
                for name in DSN_FIELDS:
                    if block.get(name) and name not in out:
                        out[name] = squash(str(block.get(name)))
        elif ctype == "text/plain" and "_text" not in out:
            body = part.get_payload(decode=True) or b""
            out["_text"] = body.decode(part.get_content_charset() or "utf-8", "replace")
    if "Diagnostic-Code" in out:
        out["Diagnostic-Code"] = re.sub(r"^smtp\s*;\s*", "", out["Diagnostic-Code"], flags=re.I)
    if "Remote-MTA" in out:
        out["Remote-MTA"] = re.sub(r"^dns\s*;\s*", "", out["Remote-MTA"], flags=re.I)
    return out


def detect_generator(b: Bounce, text: str) -> str:
    """Body markers first: integrations may rewrite From/Subject, the body is what the MTA wrote."""
    for blob in (text[:3000], f"{b.from_email} {b.subject}"):
        for name, pattern in GENERATORS:
            if pattern.search(blob):
                return name
    return "unknown"


def extract_diagnostic(text: str) -> str:
    """Pull the remote server's response out of a human-readable NDR."""
    for pattern in DIAGNOSTIC_PATTERNS:
        m = pattern.search(text)
        if m:
            return squash(m.group(1))
    m = CODE.search(text)
    if m:  # no known wrapper: take the line around the first code
        start = max(0, text.rfind("\n", 0, m.start()))
        return squash(text[start:start + 400])
    return squash(text[:400])


def join_continuations(diagnostic: str) -> str:
    """Gmail wraps long responses as '421-4.7.0 ... 421-4.7.0 ...': drop the repeated prefixes so text matches."""
    m = CODE.search(diagnostic)
    if not m or not m.group(0)[3:4] == "-":
        return diagnostic
    return diagnostic[:m.end()] + diagnostic[m.end():].replace(f" {m.group(0)} ", " ")


def detect_provider(diagnostic: str, remote_mta: str = "") -> str:
    blob = f"{diagnostic} {remote_mta}"
    return next((name for name, pattern in PROVIDER_MARKERS if pattern.search(blob)), "unknown")


def _code_key(code: str) -> tuple[int, ...]:
    return tuple(int(x) for x in code.split("."))


def _score(entry: dict[str, Any], provider: str, basic: str, enhanced: str, tags: list[str], diag: str) -> int:
    """How specifically a code-book entry matches; -1 when any field it sets does not match."""
    score = 0
    if entry.get("provider", "any") != "any":
        if entry["provider"] != provider:
            return -1
        score += 1
    if "enhanced" in entry:
        if entry["enhanced"] != enhanced:
            return -1
        score += 2
    if "enhanced_range" in entry:
        lo, hi = entry["enhanced_range"]
        if not enhanced or not _code_key(lo) <= _code_key(enhanced) <= _code_key(hi):
            return -1
        score += 2
    if "basic" in entry:
        if entry["basic"] != basic:
            return -1
        score += 1
    if "tag" in entry:
        if not any(re.fullmatch(entry["tag"], t) for t in tags):
            return -1
        score += 3
    if "text" in entry:
        if not re.search(entry["text"], diag, re.I):
            return -1
        score += 2
    return score


def lookup(codebook: dict[str, Any], provider: str, basic: str, enhanced: str, tags: list[str],
           diagnostic: str) -> tuple[dict[str, Any] | None, str]:
    """Code-book entry (most specific wins), then keywords, then RFC 3463 class. Returns (entry, match_type)."""
    scored = [(_score(e, provider, basic, enhanced, tags, diagnostic), -i, e) for i, e in enumerate(codebook["entries"])]
    best = max(scored, key=lambda t: (t[0], t[1]))
    if best[0] >= 0:
        return best[2], "code"
    for kw in codebook["keywords"]:
        if re.search(kw["pattern"], diagnostic, re.I):
            return {"id": "keyword", "meaning": f"Keyword match: {kw['pattern'][:40]}", **kw}, "keyword"
    for fb in codebook["class_fallbacks"]:
        if enhanced.startswith(fb["prefix"]) and (not fb.get("basic") or basic in fb["basic"]):
            return {"id": "class:" + fb["prefix"], **fb}, "class"
    return None, "none"


def bounce_class(enhanced: str, basic: str, category: str) -> str:
    """Hard / soft / block: the split most bounce audits use."""
    if enhanced.startswith("4") or basic.startswith("4"):
        return "soft"
    if category == "bad_data" or (category in ("noise", "unknown") and enhanced.startswith("5.1")):
        return "hard"
    return "other" if category in ("noise", "unknown") else "block"


def decode(b: Bounce, codebook: dict[str, Any], provider_hint: str = "unknown") -> Decoded:
    """Decode one bounce. Never raises on odd text; unclassifiable bounces come back as 'unknown'."""
    try:
        dsn = parse_dsn(b.raw_body)
    except Exception:  # malformed MIME: fall back to the text bodies
        dsn = {}
    text = dsn.get("_text") or b.text_body or strip_html(b.html_body) or b.raw_body
    diagnostic = join_continuations(dsn.get("Diagnostic-Code") or extract_diagnostic(text))
    source = ("dsn" if "Diagnostic-Code" in dsn else "text_body" if b.text_body else
              "html_body" if b.html_body else "raw_body")

    m = CODE.search(diagnostic) or CODE.search(text)
    basic, enhanced = (m.group(1), m.group(2)) if m else ("", "")
    if not enhanced:
        em = ENHANCED.search(dsn.get("Status", "")) or ENHANCED.search(diagnostic)
        enhanced = em.group(1) if em else ""
    if not basic:
        bm = BASIC.search(diagnostic)
        basic = bm.group(1) if bm else ""
    tags = TAG.findall(diagnostic) or TAG.findall(text)

    rejecting = detect_provider(diagnostic, dsn.get("Remote-MTA", ""))
    entry, match_type = lookup(codebook, rejecting if rejecting != "unknown" else provider_hint,
                               basic, enhanced, tags, diagnostic)
    if entry is None:  # no usable response line (e.g. cut off by the sequencer): try the notice's own wording
        hit = next((h for h in codebook.get("headlines", []) if re.search(h["pattern"], text, re.I)), None)
        entry, match_type = (hit, "headline") if hit else (None, "none")
    entry = entry or {}
    category = entry.get("category", "unknown")
    unknown_meaning = ("Policy block (RFC 3463 5.7.x), needs review" if enhanced.startswith("5.7")
                       else "Unclassified, raw text kept")
    return Decoded(
        generator=detect_generator(b, text), rejecting_provider=rejecting, basic_code=basic,
        enhanced_code=enhanced, provider_tags=",".join(tags), diagnostic=diagnostic[:500], decode_source=source,
        codebook_id=entry.get("id", ""), match_type=match_type, meaning=entry.get("meaning", unknown_meaning),
        category=category, fault_side=entry.get("fault_side", "unknown"), ambiguous=bool(entry.get("ambiguous")),
        bounce_class=bounce_class(enhanced, basic, category),
    )
